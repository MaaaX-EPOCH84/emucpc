# Installs the Git pre-commit hook that runs the local CI (ci/run.sh) before
# every commit; a failing CI stops the commit. `git commit --no-verify`
# skips it, for an emergency. The hook lives outside the repository: install
# it again on a new clone.
#
# Usage: ci/install-hook.sh
#
# The hook runs the CI on the working tree, not only on what is staged.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
hook=$(git -C "$root" rev-parse --git-path hooks/pre-commit)
[[ $hook = /* ]] || hook=$root/$hook
if [[ -e $hook ]] && ! grep -q 'emucpc local CI' "$hook"; then
    echo "ci/install-hook.sh: $hook exists and is not ours, left untouched" >&2
    exit 1
fi
mkdir -p "$(dirname "$hook")"
cat >"$hook" <<'HOOK'
#!/bin/sh
# emucpc local CI: generated by ci/install-hook.sh.
exec "$(git rev-parse --show-toplevel)/ci/run.sh"
HOOK
chmod +x "$hook"
echo "installed $hook"
